var missing = /* @__PURE__ */ new Set();
function lookup(dictionary, key) {
	return key.split(".").reduce((node, part) => node && typeof node === "object" ? node[part] : void 0, dictionary);
}
/**
* Resolves a key against the selected dictionary, falling back to English and
* then to the key itself. In development a missing translation is reported once
* per key, which is how new interface text is caught before release.
*/
function translate(language, key, vars) {
	let value = lookup(dictionaries[language] || {}, key);
	if (value === void 0 || value === "") {
		const fallback = lookup(en, key);
		if (fallback === void 0) return key;
		if (language !== "en") {
			const marker = `${language}:${key}`;
			missing.add(marker);
		}
		value = fallback;
	}
	if (typeof value !== "string") return key;
	if (!vars) return value;
	return value.replace(/\{(\w+)\}/g, (match, name) => vars[name] === void 0 || vars[name] === null ? match : String(vars[name]));
}
